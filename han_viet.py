def han_viet_name(cn_text: str) -> str:
    """Convert a Chinese term to Hán-Việt; return empty if any reading is unknown."""
    parts = []
    for ch in cn_text:
        if ch in HAN_VIET:
            parts.append(HAN_VIET[ch])
        elif '\u4e00' <= ch <= '\u9fff':
            return ''
    if not parts:
        return ''
    return ' '.join(p.capitalize() for p in parts)


